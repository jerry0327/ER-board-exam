import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  MANAGED_AUDIO_NAMESPACE,
  loadManagedAudioState,
} from "./lib/managed-audio-manifest.mjs";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(projectRoot, "worker/managed-audio-manifest.generated.ts");
const state = await loadManagedAudioState(projectRoot);
const rows = state.assets.map((asset) => [
  asset.logicalPath,
  asset.storedPath,
  asset.r2Key,
  asset.contentType,
  asset.rawBytes,
  asset.storedBytes,
  asset.rawSha256,
  asset.storedSha256,
]);

const source = `/* This file is generated by scripts/generate-managed-audio-manifest.mjs. */
export const MANAGED_AUDIO_NAMESPACE = ${JSON.stringify(MANAGED_AUDIO_NAMESPACE)};
export const MANAGED_AUDIO_MANIFEST_SET_SHA256 = ${JSON.stringify(state.manifestSetSha256)};
export const MANAGED_AUDIO_ASSETS_MERKLE_ROOT = ${JSON.stringify(state.assetsMerkleRoot)};
export const MANAGED_AUDIO_ASSET_ROWS = ${JSON.stringify(rows)} as const;
`;

let previous = null;
try {
  previous = await readFile(outputPath, "utf8");
} catch {
  // First generation.
}
if (previous !== source) await writeFile(outputPath, source, "utf8");
console.log(`Generated exact managed-audio allowlist for ${rows.length} assets.`);
